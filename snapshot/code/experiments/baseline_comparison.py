    # ============================================================
    log.info("Generating figures...")

    # --- Figure 1: Radar chart (5 models × 4 normalized metrics) ---
    # For radar, normalize each metric so that higher = better, then to [0, 1]
    radar_data = {}
    for task in ['A', 'B', 'C', 'D']:
        metric = PRIMARY_METRIC[task]
        means = {}
        for m in MODELS:
            vals = df[(df['task'] == task) & (df['model'] == m)][metric].values
            means[m] = float(vals.mean())
        # Convert to "higher is better"
        if BETTER[task] == 'lower':
            # Use 1/(1+x) for lower-is-better metrics
            scores = {m: 1.0 / (1.0 + abs(v)) for m, v in means.items()}
        else:
            scores = {m: v for m, v in means.items()}
        # Normalize to [0, 1]
        max_s = max(scores.values()) if max(scores.values()) > 0 else 1.0
        min_s = min(scores.values())
        range_s = max(max_s - min_s, 1e-9)
        radar_data[task] = {m: (scores[m] - min_s) / range_s for m in MODELS}

    # Plot radar
    fig = plt.figure(figsize=(8, 7))
    ax = fig.add_subplot(111, polar=True)
    n_axes = 4
    angles = np.linspace(0, 2 * np.pi, n_axes, endpoint=False).tolist()
    angles += angles[:1]  # close

    colors = {'LIF': '#9E9E9E', 'AdaptiveLIF': '#7CB344',
              'RNN': '#FB8C00', 'GRU': '#5B8DB8', 'TAN': '#1A1A1A'}
    for m in MODELS:
        values = [radar_data[t][m] for t in ['A', 'B', 'C', 'D']]
        values += values[:1]
        ax.plot(angles, values, color=colors[m], linewidth=2, label=m,
                linestyle='-' if m == 'TAN' else '--')
        ax.fill(angles, values, color=colors[m], alpha=0.1 if m == 'TAN' else 0.05)

    ax.set_xticks(angles[:-1])
    ax.set_xticklabels(['A: Habituation', 'B: Noise', 'C: Phototaxis', 'D: Noisy Photo.'],
                       fontsize=10)
    ax.set_ylim(0, 1.05)
    ax.set_yticks([0.25, 0.5, 0.75, 1.0])
    ax.set_yticklabels(['0.25', '0.50', '0.75', '1.00'], fontsize=8, color='gray')
    ax.set_title("Part 2 — 5-Model Comparison: Normalized Performance Radar",
                 fontsize=12, fontweight='bold', pad=20)
    ax.legend(loc='upper right', bbox_to_anchor=(1.3, 1.1), fontsize=9)
    ax.grid(True, linestyle='--', alpha=0.5)
    fig.savefig(FIG_DIR / "fig_radar.png", dpi=200, facecolor='white',
                bbox_inches='tight')
    plt.close(fig)
    log.info(f"Radar chart saved: {FIG_DIR / 'fig_radar.png'}")

    # --- Figure 2: 4-panel bar chart with error bars ---
    fig, axs = plt.subplots(1, 4, figsize=(14, 4), constrained_layout=True)
