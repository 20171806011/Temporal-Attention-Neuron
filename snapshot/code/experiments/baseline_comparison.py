def run_experiment_A(model_name, seed, trained_policy=None):
    """Step input habituation test."""
    np.random.seed(seed)
    signal = np.concatenate([np.zeros(5), np.ones(25)])
    spikes = []
    if model_name in ('RNN', 'GRU'):
        spikes, _ = rnn_inference(trained_policy, signal)
    elif model_name == 'LIF':
        n = LIFNeuron(lambda_leak=0.5, threshold=2.0)
        spikes = np.array([n.forward(x) for x in signal])
    elif model_name == 'AdaptiveLIF':
        n = AdaptiveLIFNeuron(lambda_leak=0.5, threshold0=2.0,
                               alpha=0.3, rho=0.05)
        spikes = np.array([n.forward(x) for x in signal])
    elif model_name == 'TAN':
        n = TANNeuron(window_size=10, lambda_leak=0.5, threshold=0.3,
                      noise_tolerance=0.0, use_gating=True,
                      use_asym_rect=False, beta=1.0)
        spikes = np.array([n.forward(x) for x in signal])

    # Decay time
    onset = 5
    post = spikes[onset:]
    if post.sum() == 0:
        decay_time = 0.0
    else:
        rate = np.convolve(post, np.ones(3) / 3, mode='same')
        peak = rate.max()
        threshold = 0.1 * peak
        peak_idx = np.argmax(rate)
        below = np.where(rate[peak_idx:] < threshold)[0]
        decay_time = float(below[0] + peak_idx) if len(below) > 0 else float(len(post))

    return {
        'decay_time': decay_time,
        'total_spikes': int(spikes.sum()),
        'early_spikes': int(spikes[onset:onset+3].sum()),
    }


def run_experiment_B(model_name, seed, trained_policy=None):
    """Noisy light signal spike-rate test."""
