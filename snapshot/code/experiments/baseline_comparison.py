import torch
import torch.nn as nn
import torch.optim as optim

torch.manual_seed(0)
DEVICE = torch.device('cpu')


class RNNPolicy(nn.Module):
    """1-hidden-unit Elman RNN. Input = light intensity (scalar).
    Output = sigmoid(spike probability). Threshold at 0.5 to get binary spike.
    """
    def __init__(self, hidden_dim=8):
        super().__init__()
        self.rnn = nn.RNN(input_size=1, hidden_size=hidden_dim,
                          nonlinearity='tanh', batch_first=True)
        self.fc = nn.Linear(hidden_dim, 1)

    def forward(self, x_seq):
        # x_seq: (batch, seq, 1)
        out, _ = self.rnn(x_seq)
        logits = self.fc(out)              # (batch, seq, 1)
        return logits.squeeze(-1)          # (batch, seq)


class GRUPolicy(nn.Module):
    """1-hidden-unit GRU."""
    def __init__(self, hidden_dim=8):
        super().__init__()
        self.gru = nn.GRU(input_size=1, hidden_size=hidden_dim, batch_first=True)
        self.fc = nn.Linear(hidden_dim, 1)

    def forward(self, x_seq):
        out, _ = self.gru(x_seq)
        logits = self.fc(out)
        return logits.squeeze(-1)


def train_rnn_policy(model_kind, task, seed=0, epochs=200, lr=1e-2):
    """Train an RNN/GRU policy via imitation learning on a TAN-generated
    expert trajectory. We use BCE loss on the binary spike sequence.
    """
    torch.manual_seed(seed)
    np.random.seed(seed)

    if model_kind == 'RNN':
        model = RNNPolicy(hidden_dim=8)
    elif model_kind == 'GRU':
        model = GRUPolicy(hidden_dim=8)
    else:
        raise ValueError(model_kind)
    model.to(DEVICE)

    # Generate one expert trajectory using a TAN agent
    expert_inputs, expert_spikes = generate_expert_trajectory(task, seed=seed)
    # expert_inputs: (T,) numpy, expert_spikes: (T,) numpy {0,1}

    x = torch.tensor(expert_inputs, dtype=torch.float32, device=DEVICE).view(1, -1, 1)
    y = torch.tensor(expert_spikes, dtype=torch.float32, device=DEVICE).view(1, -1)

    opt = optim.Adam(model.parameters(), lr=lr)
    loss_fn = nn.BCEWithLogitsLoss()

    model.train()
    for epoch in range(epochs):
        opt.zero_grad()
        logits = model(x)
        loss = loss_fn(logits, y)
        loss.backward()
        opt.step()

    return model


def generate_expert_trajectory(task, seed=0):
    """Generate (inputs, spikes) from a TAN agent for use as imitation target."""
    np.random.seed(seed)
    if task == 'A':
        # Step input, TAN spikes at onset then habituates
        signal = np.concatenate([np.zeros(5), np.ones(25)])
        tan = TANNeuron(window_size=10, lambda_leak=0.5, threshold=0.3,
                        noise_tolerance=0.0, use_gating=True,
                        use_asym_rect=False, beta=1.0)
        spikes = np.array([tan.forward(s) for s in signal])
        return signal, spikes

    elif task == 'B':
        time_steps = 60
        base = np.concatenate([np.zeros(15), np.ones(45) * 1.5])
        noise = np.random.normal(0, 0.4, time_steps)
        signal = np.clip(base + noise, 0, None)
        tan = TANNeuron(window_size=10, lambda_leak=0.8, threshold=1.0,
                        noise_tolerance=0.0, use_gating=True,
                        use_asym_rect=False, beta=1.0)
        spikes = np.array([tan.forward(s) for s in signal])
        return signal, spikes

    elif task in ('C', 'D'):
        # Use a TAN agent's full trajectory as expert demonstration
        time_steps = 300 if task == 'C' else 250
        agent = Bioton(brain_type='TAN', start_pos=50.0,
                       noisy_env=(task == 'D'),
                       noise_tolerance=0.6 if task == 'D' else 0.0)
        inputs = []
        spikes = []
        rng = np.random.RandomState(seed)
        for _ in range(time_steps):
            if task == 'C':
                light = get_clean_light(agent.pos)
            else:
                light = get_noisy_light(agent.pos, noise_level=0.5, rng=rng)
            inputs.append(light)
            s = agent.brain.forward(light)
            agent.velocity = 0.6 * agent.velocity + 0.8 * s
            agent.pos += agent.velocity
            spikes.append(s)
        return np.array(inputs), np.array(spikes)

    else:
        raise ValueError(task)


def rnn_inference(model, signal, hidden=None):
    """Run trained RNN/GRU on a 1D signal, return (binary spike sequence, new hidden).

    If hidden is None, the model initializes it internally.
    Returns (spikes: np.ndarray shape (T,), new_hidden).
    """
    model.eval()
    with torch.no_grad():
        x = torch.tensor(signal, dtype=torch.float32, device=DEVICE).view(1, -1, 1)
        # Forward through RNN/GRU manually to capture hidden state
        if isinstance(model, RNNPolicy):
            out, new_hidden = model.rnn(x, hidden)
            logits = model.fc(out).squeeze(-1)  # (1, T)
        elif isinstance(model, GRUPolicy):
            out, new_hidden = model.gru(x, hidden)
            logits = model.fc(out).squeeze(-1)  # (1, T)
        else:
            logits = model(x)
            new_hidden = None
        probs = torch.sigmoid(logits).squeeze(0).cpu().numpy()
        if probs.ndim == 0:
            probs = probs.reshape(1)
    return (probs > 0.5).astype(int), new_hidden


