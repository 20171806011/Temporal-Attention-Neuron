def get_clean_light(x):
    return 10.0 * np.exp(-((x - 80.0) ** 2) / (2 * 15.0 ** 2))


def get_noisy_light(x, noise_level=0.5, rng=None):
    clean = get_clean_light(x)
    if rng is None:
        n = np.random.normal(0, noise_level)
    else:
        n = rng.normal(0, noise_level)
    return max(0.0, clean + n)


class Bioton:
    """Generic agent wrapper. brain_type in {LIF, AdaptiveLIF, TAN, RNN, GRU}.

    For RNN/GRU, the brain is a frozen trained policy; we feed it the current
    light intensity as a 1-step sequence and read out the spike.
    """
    def __init__(self, brain_type='TAN', start_pos=50.0, noisy_env=False,
                 noise_tolerance=0.0, trained_policy=None):
        self.brain_type = brain_type
        self.trained_policy = trained_policy
        self.pos = start_pos
        self.velocity = 0.0
        self.pos_log = []
        self.spike_log = []
        self.noisy_env = noisy_env
        self.hidden = None  # for RNN/GRU stateful inference
        # Instantiate SNN brain if applicable
        if brain_type == 'LIF':
            thr = 2.5 if noisy_env else 2.0
            self.brain = LIFNeuron(lambda_leak=0.5, threshold=thr)
        elif brain_type == 'AdaptiveLIF':
            thr0 = 2.5 if noisy_env else 2.0
            self.brain = AdaptiveLIFNeuron(lambda_leak=0.5, threshold0=thr0,
                                            alpha=0.3, rho=0.05)
        elif brain_type == 'TAN':
            self.brain = TANNeuron(window_size=5, lambda_leak=0.5,
                                   threshold=0.5,
                                   noise_tolerance=noise_tolerance,
                                   use_gating=True, use_asym_rect=True)
        elif brain_type in ('RNN', 'GRU'):
            self.brain = None  # uses trained_policy instead
        else:
            raise ValueError(brain_type)

    def step(self, light):
        if self.brain_type in ('RNN', 'GRU'):
            # Stateful 1-step inference: pass current light + previous hidden
            spike_seq, self.hidden = rnn_inference(
                self.trained_policy, np.array([light]), hidden=self.hidden)
            spike = int(spike_seq[0])
        else:
            spike = self.brain.forward(light)
        self.velocity = 0.6 * self.velocity + 0.8 * spike
        self.pos += self.velocity
        self.pos_log.append(self.pos)
        self.spike_log.append(spike)


