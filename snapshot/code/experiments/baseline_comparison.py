class LIFNeuron:
    """Classical LIF."""
    def __init__(self, lambda_leak=0.5, threshold=2.0):
        self.lambda_leak = lambda_leak
        self.threshold = threshold
        self.h = 0.0

    def forward(self, x):
        self.h = self.lambda_leak * self.h + x
        if self.h > self.threshold:
            spike = 1
            self.h = 0.0
        else:
            spike = 0
        return spike

    def reset(self):
        self.h = 0.0


class AdaptiveLIFNeuron:
    """LIF with slow threshold adaptation. Threshold rises after each spike,
    slowly decays back to baseline. This produces habituation.
    """
    def __init__(self, lambda_leak=0.5, threshold0=2.0,
                 alpha=0.3,         # threshold increment per spike
                 rho=0.05):         # threshold recovery rate (per step)
        self.lambda_leak = lambda_leak
        self.threshold0 = threshold0
        self.threshold = threshold0
        self.alpha = alpha
        self.rho = rho
        self.h = 0.0

    def forward(self, x):
        self.h = self.lambda_leak * self.h + x
        if self.h > self.threshold:
            spike = 1
            self.h = 0.0
            # Threshold increments after firing
            self.threshold = self.threshold + self.alpha
        else:
            spike = 0
        # Threshold recovery toward baseline
        self.threshold = (1 - self.rho) * self.threshold + self.rho * self.threshold0
        return spike

    def reset(self):
        self.h = 0.0
        self.threshold = self.threshold0


class TANNeuron:
    """Temporal Attention Neuron (full model)."""
    def __init__(self, window_size=5, lambda_leak=0.5, threshold=0.5,
                 noise_tolerance=0.0, use_gating=True, use_asym_rect=True,
                 beta=1.0):
        self.window_size = window_size
        self.lambda_leak = lambda_leak
        self.threshold = threshold
        self.noise_tolerance = noise_tolerance
        self.use_gating = use_gating
        self.use_asym_rect = use_asym_rect
        self.beta = beta
        self.h = 0.0
        self.W_q = np.array([2.0])
        self.W_k = np.array([1.0])
        self.W_v = np.array([1.0])
        self.history = np.zeros(window_size)

    def softmax(self, x):
        e_x = np.exp(self.beta * (x - np.max(x)))
        return e_x / (e_x.sum(axis=0) + 1e-9)

    def forward(self, x):
        self.history = np.roll(self.history, -1)
        self.history[-1] = x
        S_t = x - np.mean(self.history)
        if self.use_asym_rect:
            S_t = np.maximum(0, S_t - self.noise_tolerance)
        Q = S_t * self.W_q
        K = self.history * self.W_k
        V = self.history * self.W_v
        att = self.softmax(Q * K)
        C_t = np.sum(att * V)
        if self.use_gating:
            g = np.tanh(S_t) if self.use_asym_rect else np.tanh(abs(S_t))
            A_t = g * C_t
        else:
            A_t = C_t * 0.5
        self.h = self.lambda_leak * self.h + A_t
        if self.h > self.threshold:
            spike = 1
            self.h = 0.0
        else:
            spike = 0
        return spike

    def reset(self):
        self.h = 0.0
        self.history = np.zeros(self.window_size)


